export function generateCssAnimation(layers: GraphicLayer[], keyframes: AnimationKeyframe[]): string {
  let css = `/* Generated by MEDHĀ Graphic & Motion Animation Studio */\n`;
  layers.forEach((layer) => {
    const layerKfs = keyframes.filter(k => k.layerId === layer.id);
    if (layerKfs.length > 0) {
      const animName = `anim_${layer.name.toLowerCase().replace(/[^a-z0-9]/g, '_')}`;
      css += `@keyframes ${animName} {\n`;
      layerKfs.forEach((kf) => {
        const percent = Math.round((kf.timeSec / 2.0) * 100);
        css += `  ${percent}% { ${kf.property}: ${kf.value}${kf.property === 'rotation' ? 'deg' : (kf.property === 'opacity' ? '' : 'px')}; }\n`;
      });
      css += `}\n\n`;
      css += `.${animName}_target {\n`;
      css += `  animation: ${animName} 2s infinite alternate ease-in-out;\n`;
      css += `}\n\n`;
    }
  });
  return css;
}

export function exportSvgCanvas(layers: GraphicLayer[]): string {
  let svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 600 400" width="100%" height="100%">\n`;
  layers.forEach((layer) => {
    if (!layer.visible) return;
    if (layer.type === 'rectangle') {
      svg += `  <rect x="${layer.x}" y="${layer.y}" width="${layer.width}" height="${layer.height}" fill="${layer.fill}" stroke="${layer.stroke}" stroke-width="${layer.strokeWidth}" opacity="${layer.opacity}" transform="rotate(${layer.rotation} ${layer.x + layer.width/2} ${layer.y + layer.height/2})" rx="12" />\n`;
    } else if (layer.type === 'ellipse') {
      const cx = layer.x + layer.width / 2;
      const cy = layer.y + layer.height / 2;
      svg += `  <ellipse cx="${cx}" cy="${cy}" rx="${layer.width/2}" ry="${layer.height/2}" fill="${layer.fill}" stroke="${layer.stroke}" stroke-width="${layer.strokeWidth}" opacity="${layer.opacity}" />\n`;
    } else if (layer.type === 'text') {
      svg += `  <text x="${layer.x}" y="${layer.y + 24}" fill="${layer.fill}" font-family="JetBrains Mono, sans-serif" font-size="18" font-weight="bold" opacity="${layer.opacity}">${layer.content || ''}</text>\n`;
    }
  });
  svg += `</svg>`;
  return svg;
}
